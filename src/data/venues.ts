const normalizeSearchText = (value: string) => value.trim().toLocaleLowerCase();

const getSearchValues = (venue: Venue) => [
  venue.name,
  venue.nameJa,
  venue.nameZh,
  venue.city,
  venue.country,
  venue.prefecture,
  venue.region,
  venue.category,
  ...(venue.aliases ?? []),
];

export const getVenueById = (venueId: string) =>
  venues.find((venue) => venue.id === venueId);

export const getVenueRegion = (venue: Venue) =>
  venue.region ?? venue.prefecture ?? venue.city ?? "Other";

export const getVenueSearchText = (venue: Venue) =>
  getSearchValues(venue)
    .filter((value): value is string => Boolean(value))
    .map(normalizeSearchText)
    .join(" ");

export const venueMatchesSearch = (venue: Venue, search: string) => {
  const normalizedSearch = normalizeSearchText(search);
  return !normalizedSearch || getVenueSearchText(venue).includes(normalizedSearch);
};

export const compareVenues = (first: Venue, second: Venue) => {
  const firstRegionIndex = venueRegionOrder.indexOf(getVenueRegion(first));
  const secondRegionIndex = venueRegionOrder.indexOf(getVenueRegion(second));
  const normalizedFirstIndex = firstRegionIndex === -1 ? Number.POSITIVE_INFINITY : firstRegionIndex;
  const normalizedSecondIndex = secondRegionIndex === -1 ? Number.POSITIVE_INFINITY : secondRegionIndex;

  if (normalizedFirstIndex !== normalizedSecondIndex) {
    return normalizedFirstIndex - normalizedSecondIndex;
  }

  return first.name.localeCompare(second.name);
};

export const groupVenuesByRegion = (items: Venue[]) =>
  [...items].sort(compareVenues).reduce<Array<{ region: string; venues: Venue[] }>>((groups, venue) => {
    const region = getVenueRegion(venue);
    const existingGroup = groups.find((group) => group.region === region);

    if (existingGroup) {
      existingGroup.venues.push(venue);
      return groups;
    }

    return [...groups, { region, venues: [venue] }];
  }, []);
